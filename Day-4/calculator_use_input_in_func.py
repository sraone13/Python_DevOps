
def addition(num1, num2):
    add = num1 + num2
    return add

def mul(num1, num2):
    m = num1 * num2
    return m

def sub(num1, num2):
    s = num1 - num2
    return s

x = addition(5, 6)
print("Addition value =", x)

y = mul(5, 6)
print("mul value =", y)

z = sub(6, 8)
print("sub value =", z)
